const translations: Record<AppLanguage, TranslationTable> = {
  en,
  "zh-TW": zhTW,
  th,
};

export const languageOptions: Array<{
  value: AppLanguage;
  label: string;
}> = [
  { value: "en", label: "English" },
  { value: "zh-TW", label: "繁體中文" },
  { value: "th", label: "ไทย" },
];

export const languageLocales: Record<AppLanguage, string> = {
  en: "en",
  "zh-TW": "zh-TW",
  th: "th-TH",
};

type TranslationValues = Record<string, string | number>;

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  values: TranslationValues = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.replaceAll(`{{${name}}}`, String(value)),
    translations[language][key],
  );
}

type I18nContextValue = {
  language: AppLanguage;
  locale: string;
  t: (key: TranslationKey, values?: TranslationValues) => string;
};

const I18nContext = createContext<I18nContextValue>({
  language: "zh-TW",
  locale: languageLocales["zh-TW"],
  t: (key, values) => translate("zh-TW", key, values),
});

export function I18nProvider({
  language,
  children,
}: {
  language: AppLanguage;
  children: ReactNode;
}) {
  const locale = languageLocales[language];
  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      locale,
      t: (key, values) => translate(language, key, values),
    }),
    [language, locale],
  );

  useEffect(() => {
    document.documentElement.lang = language === "zh-TW" ? "zh-Hant" : locale;
    document.title = translate(language, "document.title");
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute(
        "content",
        translate(language, "document.description"),
      );
  }, [language, locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
